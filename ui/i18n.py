def detect_system_language():
    candidates = []
    if sys.platform == "win32":
        try:
            import ctypes

            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            candidates.append(locale.windows_locale.get(lang_id, ""))
        except Exception:
            pass
    candidates.extend(
        [
            os.environ.get("LANGUAGE", ""),
            os.environ.get("LC_ALL", ""),
            os.environ.get("LC_MESSAGES", ""),
            os.environ.get("LANG", ""),
        ]
    )
    try:
        candidates.append(locale.getdefaultlocale()[0] or "")
    except Exception:
        pass

    for candidate in candidates:
        normalized = str(candidate or "").replace("-", "_").lower()
        if normalized.startswith("zh"):
            return "zh"
    return "en"


def set_language(lang):
    global _current_lang
    if lang in TRANSLATIONS:
        _current_lang = lang

def get_language():
    return _current_lang

def tr(key, **kwargs):
    text = TRANSLATIONS.get(_current_lang, TRANSLATIONS["zh"]).get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text
